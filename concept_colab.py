# 8.  UNIFIED FRAMEWORK  (Algorithm 1 in paper)
# ──────────────────────────────────────────────────────────

# Reward / cost parameters
COST_PUMP    = {'LOW': 1.0, 'MEDIUM': 2.5, 'HIGH': 4.0}
COST_MONITOR = 1.5
COST_BARRIER = 20.0
COST_FAILURE = 50.0
U_MIN        = -30.0   # satisficing threshold (min cumulative reward)
DELTA        = 0.10    # max allowed failure probability
LAMBDA_VOI   = 2.0     # weight on VoI term
MU_OV        = 1.5     # weight on option value term
GAMMA        = 0.95    # discount factor

ACTIONS = ['LOW', 'MEDIUM', 'HIGH']


def reward(action: str, s: int, monitor: bool, barrier: bool) -> float:
    r = -COST_PUMP[action]
    if monitor:
        r -= COST_MONITOR
    if barrier:
        r -= COST_BARRIER
    if s == 1:
        r -= COST_FAILURE
    return r


def satisficing_check(pi_r: np.ndarray, pi_m: np.ndarray,
                      h: float, n_samples: int = 300) -> bool:
    """
    Monte Carlo estimate of P(cumulative utility >= U_min).
    Returns True if the constraint is satisfied.
    """
    total_r = []
    for _ in range(n_samples):
        ri = rng.choice(len(REGIMES), p=pi_r)
        mi = rng.choice(len(MODELS),  p=pi_m)
        regime = REGIMES[ri]
        h_sim  = h
        cum_r  = 0.0
        for step in range(T):
            h_sim = np.clip(h_sim + RECHARGE[regime] - PUMP_DEMAND, 0.05, 1.0)
            s_sim = 1 if h_sim <= H_CRIT else 0
            cum_r += (GAMMA ** step) * reward('LOW', s_sim, False, False)
        total_r.append(cum_r)
    p_viable = np.mean(np.array(total_r) >= U_MIN)
    return p_viable >= (1 - DELTA)


def voi_estimate(pi_r: np.ndarray, pi_m: np.ndarray,
                 h: float, obs: float, sigma: float) -> float:
    """
    Myopic VoI: expected improvement in best-action value from one observation.
    """
    v_current = 0.0
    for ri, rp in enumerate(pi_r):
        for mi, mp in enumerate(pi_m):
            h_next = np.clip(h + RECHARGE[REGIMES[ri]] - PUMP_DEMAND, 0.05, 1.0)
            s = 1 if h_next <= H_CRIT else 0
            v_current += rp * mp * reward('LOW', s, False, False)

    # Expected value after observing (update beliefs with sampled obs)
    v_post = 0.0
    for _ in range(50):
        obs_s = float(rng.normal(obs, sigma))
        log_r = np.array([log_likelihood_regime(obs_s, h, reg, sigma) for reg in REGIMES])
        log_r -= log_r.max()
        pi_r2 = pi_r * np.exp(log_r);  pi_r2 /= pi_r2.sum()

        log_m = np.array([log_likelihood_model(obs_s, h, mod, sigma) for mod in MODELS])
        log_m -= log_m.max()
        pi_m2 = pi_m * np.exp(log_m);  pi_m2 /= pi_m2.sum()

        v2 = 0.0
        for ri, rp in enumerate(pi_r2):
            for mi, mp in enumerate(pi_m2):
                h_next = np.clip(h + RECHARGE[REGIMES[ri]] - PUMP_DEMAND, 0.05, 1.0)
                s = 1 if h_next <= H_CRIT else 0
                v2 += rp * mp * reward('LOW', s, False, False)
        v_post += v2
    v_post /= 50
    return max(0.0, v_post - v_current)


def option_value(pi_r: np.ndarray, h: float) -> float:
    """
    Option value of delaying barrier construction.
    OV = V_delay(b) - V_commit(b); positive means delay is preferred.
    """
    # V_commit: immediate barrier cost amortised over horizon
    v_commit = -COST_BARRIER + sum(
        GAMMA**t * (-COST_PUMP['LOW'])
        for t in range(T)
    )
    # V_delay: expected value without barrier, weighted by regime
    v_delay = 0.0
    for ri, rp in enumerate(pi_r):
        h_sim = h
        cum = 0.0
        for step in range(T):
            h_sim = np.clip(h_sim + RECHARGE[REGIMES[ri]] - PUMP_DEMAND, 0.05, 1.0)
            s = 1 if h_sim <= H_CRIT else 0
            cum += GAMMA**step * reward('LOW', s, False, False)
        v_delay += rp * cum
    return max(0.0, v_delay - v_commit)


def run_unified_framework(h_traj: list, obs_seq: list,
                          pi_r_hist: np.ndarray,
                          pi_m_hist: np.ndarray) -> dict:
    """
    Execute Algorithm 1: unified robust-adaptive POMDP decision loop.
    Returns per-step decisions and cumulative reward.
    """
    results = {
        'actions': [], 'monitor': [], 'barrier': [],
        'satisficing': [], 'voi': [], 'ov': [],
        'cum_reward': 0.0, 'failures': 0
    }
    barrier_built = False

    for t in range(T):
        pi_r  = pi_r_hist[t]
        pi_m  = pi_m_hist[t]
        h     = h_traj[t]
        obs   = obs_seq[t]
        sigma = OBS_SIGMA_POST if t >= 2 else OBS_SIGMA_PRE

        # Step 1 – Satisficing check
        sat = satisficing_check(pi_r, pi_m, h)
        results['satisficing'].append(sat)

        # Step 2 – VoI (directed learning)
        voi = voi_estimate(pi_r, pi_m, h, obs, sigma) if sat else 0.0
        results['voi'].append(voi)

        # Step 3 – Option value (real options)
        ov = option_value(pi_r, h) if (sat and not barrier_built) else 0.0
        results['ov'].append(ov)

        # Step 4 – Action selection: maximise integrated objective
        best_score = -np.inf
        best_action = 'LOW'
        use_monitor = False

        for action in ACTIONS:
            for monitor in [False, True]:
                score = -COST_PUMP[action]
                if monitor:
                    score -= COST_MONITOR
                score += LAMBDA_VOI * voi + MU_OV * ov
                if score > best_score:
                    best_score = score
                    best_action = action
                    use_monitor = monitor

        # Delay barrier unless option value is negative (commit now better)
        build_barrier = (not barrier_built) and (ov < 0.0)
        if build_barrier:
            barrier_built = True

        results['actions'].append(best_action)
        results['monitor'].append(use_monitor)
        results['barrier'].append(build_barrier)

        # Reward this step
        h_next = h_traj[t + 1]
        s_next = 1 if h_next <= H_CRIT else 0
        step_r = (GAMMA ** t) * reward(best_action, s_next, use_monitor, build_barrier)
        results['cum_reward'] += step_r
        if s_next == 1:
            results['failures'] += 1

    return results


