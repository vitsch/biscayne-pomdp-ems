from scipy.stats import norm as scipy_norm

def salinity_mean_model(h: float, model: str, tipped: bool = False) -> float:
    """
    Predicted salinity signal for each intrusion model.

    M1 (sharp-interface): binary step at h_crit
    M2 (dispersive):      sigmoid – gradual increase as h falls
    M3 (tipping-point):   irreversible collapse once h < h_crit
    """
    if model == 'M1: Sharp-interface':
        return 0.90 if h <= H_CRIT else 0.10

    elif model == 'M2: Dispersive':
        k = 18.0          # sigmoid slope – moderately gradual
        return 1.0 / (1.0 + np.exp(k * (h - H_CRIT)))

    else:   # M3: Tipping-point (irreversible once crossed)
        if tipped or h <= H_CRIT:
            return 0.95   # stays high (irreversible)
        else:
            return 0.05 + 0.60 * np.exp(-10.0 * (h - H_CRIT))


def salinity_mean_regime(h: float, regime: str) -> float:
    """
    Expected salinity signal consistent with a given climate regime.
    (Uses M2 dispersive as the 'true' forward model for regime likelihoods.)
    h_next is the freshwater volume expected under the regime's recharge.
    """
    h_next = np.clip(h + RECHARGE[regime] - PUMP_DEMAND, 0.05, 1.0)
    return salinity_mean_model(h_next, 'M2: Dispersive')


def log_likelihood_regime(obs: float, h: float, regime: str,
                           sigma: float) -> float:
    mu = salinity_mean_regime(h, regime)
    return scipy_norm.logpdf(obs, loc=mu, scale=sigma)


def log_likelihood_model(obs: float, h: float, model: str,
                          sigma: float, tipped: bool = False) -> float:
    mu = salinity_mean_model(h, model, tipped)
    return scipy_norm.logpdf(obs, loc=mu, scale=sigma)


