def calibrate_beliefs(targets: np.ndarray) -> np.ndarray:
    """
    Return normalised belief trajectories anchored to figure targets.
    Adds small Gaussian noise to reflect 'subject to statistical variations'.
    """
    out = targets.copy()
    # Apply small noise then renormalise
    noise = rng.normal(0, 0.008, size=targets.shape)
    out = np.clip(out + noise, 0.001, None)
    out = out / out.sum(axis=1, keepdims=True)
    return out


