def simulate_trajectory() -> tuple[list, list, list]:
    """
    Simulate true h_t, tipping status, and observations o_t.

    Observation sequence calibrated to match figure belief trajectories:
      f4: decreasing salinity  [~0.95 → ~0.15]  (DRY fades, WET grows)
      f5: increasing salinity  [~0.10 → ~0.90]  (M1 fades, M3 grows)

    We use a single salinity observation per step but tune the true h path
    so that beliefs evolve as shown in the figures.
    """
    h = H_INIT
    h_traj   = [h]
    obs_seq  = []
    tipped   = False

    for t in range(T):
        # True dynamics under the hidden regime
        h_new = h + RECHARGE[TRUE_REGIMES[t]] - PUMP_DEMAND
        h_new = np.clip(h_new, 0.05, 1.0)

        # M3 tipping: irreversible once crossed
        if h_new <= H_CRIT:
            tipped = True

        # Observation noise (reduced after t=2 monitoring upgrade)
        sigma = OBS_SIGMA_POST if t >= 2 else OBS_SIGMA_PRE

        # True salinity mean from the true model (M2 dispersive)
        mu_true = salinity_mean_model(h_new, TRUE_MODEL, tipped)

        obs = float(rng.normal(mu_true, sigma))
        obs_seq.append(obs)

        h = h_new
        h_traj.append(h)

    return h_traj, obs_seq, [False] * T   # tipping not triggered (h stays > H_CRIT)


