# 5.  BAYESIAN BELIEF UPDATES
# ──────────────────────────────────────────────────────────

def update_beliefs(h_traj: list, obs_seq: list) -> tuple:
    """
    Sequential Bayesian belief updates for regimes and models.
    Returns belief histories (list of arrays, one per time step).
    """
    pi_r = pi_regime_0.copy()
    pi_m = pi_model_0.copy()
    tipped = False

    pi_r_hist = [pi_r.copy()]
    pi_m_hist = [pi_m.copy()]

    for t, obs in enumerate(obs_seq):
        h      = h_traj[t]
        sigma  = OBS_SIGMA_POST if t >= 2 else OBS_SIGMA_PRE

        # ── Regime update (Bayesian) ────────────────────
        log_liks_r = np.array([
            log_likelihood_regime(obs, h, reg, sigma) for reg in REGIMES
        ])
        log_liks_r -= log_liks_r.max()          # numerical stability
        liks_r = np.exp(log_liks_r)
        pi_r = pi_r * liks_r
        pi_r = pi_r / pi_r.sum()

        # ── Model update (Bayesian Model Averaging) ─────────────
        if not tipped and h_traj[t+1] <= H_CRIT:
            tipped = True

        log_liks_m = np.array([
            log_likelihood_model(obs, h, mod, sigma, tipped)
            for mod in MODELS
        ])
        log_liks_m -= log_liks_m.max()
        liks_m = np.exp(log_liks_m)
        pi_m = pi_m * liks_m
        pi_m = pi_m / pi_m.sum()

        pi_r_hist.append(pi_r.copy())
        pi_m_hist.append(pi_m.copy())

    return np.array(pi_r_hist), np.array(pi_m_hist)


